// Torn-paper outlines as CSS clip-path polygons (seeded, so the build is
// reproducible). Each edge is a random walk plus fine grain; amplitudes are in
// px from the edge (calc(100% - Npx)), so the tear keeps its size on any box.
// Writes src/styles/torn.generated.css. Run: node scripts/torn.mjs
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function rng(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

// n depths in [0, amp]: slow wander + fine grain + rare deeper bites
function edge(rand, n, amp) {
  if (!amp) return Array(n).fill(0)
  let walk = rand() * amp * 0.5
  const out = []
  for (let i = 0; i < n; i++) {
    walk += (rand() - 0.5) * amp * 0.45
    walk = Math.max(0, Math.min(amp * 0.75, walk))
    let d = walk + rand() * amp * 0.35
    if (rand() < 0.06) d += amp * 0.35
    out.push(Math.min(amp, d))
  }
  return out
}

const px = (v) => `${v.toFixed(1)}px`
const pct = (v) => `${v.toFixed(2)}%`

// edges: { top, right, bottom, left } amplitudes in px; steps per edge
function polygon(seed, { top = 0, right = 0, bottom = 0, left = 0, steps = 48, sideSteps = 24 }) {
  const rand = rng(seed)
  const pts = []
  const T = edge(rand, steps + 1, top)
  for (let i = 0; i <= steps; i++) pts.push([pct((i / steps) * 100), px(T[i])])
  const R = edge(rand, sideSteps + 1, right)
  for (let i = 1; i <= sideSteps; i++) pts.push([`calc(100% - ${px(R[i])})`, pct((i / sideSteps) * 100)])
  const B = edge(rand, steps + 1, bottom)
  for (let i = steps - 1; i >= 0; i--) pts.push([pct((i / steps) * 100), `calc(100% - ${px(B[i])})`])
  const L = edge(rand, sideSteps + 1, left)
  for (let i = sideSteps - 1; i >= 1; i--) pts.push([px(L[i]), pct((i / sideSteps) * 100)])
  // straight edges collapse to their corners
  return `polygon(${pts.map((p) => p.join(' ')).join(', ')})`
}

// The light paper core of a tear follows the same tear as the paper on top:
// same seed, 80% depth, drawn on a box 3px larger (rim of ~3-7px).
const fiber = (seed, edges) =>
  polygon(seed, Object.fromEntries(Object.entries(edges).map(([k, v]) => [k, k.endsWith('teps') ? v : v * 0.8])))

const SEAM = { top: 16, steps: 90, sideSteps: 2 }
const PANEL = { top: 7, right: 22, bottom: 8, left: 5, steps: 40, sideSteps: 30 }
const PANEL_ALT = { top: 8, right: 5, bottom: 7, left: 22, steps: 40, sideSteps: 30 }

const shapes = {
  // band that stitches one section to the next (top edge torn)
  '--torn-seam': polygon(11, SEAM),
  '--torn-seam-fiber': fiber(11, SEAM),
  // dark text panels (torn right/left side, ragged top and bottom)
  '--torn-panel': polygon(21, PANEL),
  '--torn-panel-fiber': fiber(21, PANEL),
  '--torn-panel-alt': polygon(23, PANEL_ALT),
  '--torn-panel-alt-fiber': fiber(23, PANEL_ALT),
  // cream notes and scraps
  '--torn-note': polygon(31, { top: 6, right: 6, bottom: 8, left: 5, steps: 26, sideSteps: 26 }),
  '--torn-scrap': polygon(32, { top: 10, right: 16, bottom: 9, left: 4, steps: 30, sideSteps: 14 }),
  // orange label with torn ends
  '--torn-tag': polygon(41, { top: 1.5, right: 5, bottom: 1.5, left: 5, steps: 20, sideSteps: 8 }),
  '--torn-btn': polygon(42, { top: 1.2, right: 3, bottom: 1.2, left: 3, steps: 24, sideSteps: 6 }),
}

const css = `/* generated by scripts/torn.mjs: do not edit by hand */\n:root {\n${Object.entries(shapes)
  .map(([k, v]) => `  ${k}: ${v};`)
  .join('\n')}\n}\n`
await writeFile(path.join(ROOT, 'src', 'styles', 'torn.generated.css'), css)
console.log('wrote src/styles/torn.generated.css', Object.keys(shapes).length, 'shapes')
